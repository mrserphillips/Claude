#!/usr/bin/env python3
"""Regenerates shared/defaults.lua from config.lua. Run after changing config.lua's shipped defaults:
    python3 tools/gen_defaults.py"""
import os
root = os.path.join(os.path.dirname(__file__), '..')
src = open(os.path.join(root, 'config.lua'), encoding='utf-8').read()
start = src.index('Config = {}')
body = src[start + len('Config = {}'):]
body = '\n'.join('    ' + line if line.strip() else '' for line in body.splitlines())
out = '''-- AUTO-GENERATED from config.lua by tools/gen_defaults.py - do not edit this file.
-- These are the shipped default settings. Any setting missing from your own config.lua
-- (for example after updating the resource but keeping an older config) is filled in from here,
-- so an older config.lua keeps working.
VJ_CONFIG_DEFAULTS = (function()
    local Config = {}
''' + body + '''

    return Config
end)()
'''
open(os.path.join(root, 'shared', 'defaults.lua'), 'w', encoding='utf-8').write(out)
print('shared/defaults.lua written')
